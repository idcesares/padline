const tables: Record<Lang, Table> = { en, pt, es, fr, de, it };

/** BCP 47 tag per language, for <html lang> and Intl. Portuguese is the Brazilian one. */
const LOCALE: Record<Lang, string> = {
  en: "en",
  pt: "pt-BR",
  es: "es",
  fr: "fr",
  de: "de",
  it: "it",
};

/** Each language in its own name, for the picker. */
export const LANG_NAMES: Record<Lang, string> = {
  en: "English",
  pt: "Português",
  es: "Español",
  fr: "Français",
  de: "Deutsch",
  it: "Italiano",
};

export function t(key: string, vars?: Record<string, string>): string {
  const table: Record<string, string> = tables[getLang()];
  let s = table[key] ?? en[key as Key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

/** Fills every [data-i18n], [data-i18n-ph] and [data-i18n-aria] under `root`. */
export function applyI18n(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n!);
  });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh!);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria!));
  });
  document.documentElement.lang = LOCALE[getLang()];
}

/** "2 min ago", "yesterday", "3 days ago", in the visitor's language. */
export function ago(at: number, now = Date.now()): string {
  const secs = Math.round((at - now) / 1000);
  const rtf = new Intl.RelativeTimeFormat(LOCALE[getLang()], { numeric: "auto" });
  const abs = Math.abs(secs);
  if (abs < 60) return t("ago.now");
  if (abs < 3600) return rtf.format(Math.round(secs / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(secs / 3600), "hour");
  return rtf.format(Math.round(secs / 86400), "day");
}

export function formatDate(at: number): string {
  return new Intl.DateTimeFormat(LOCALE[getLang()], {
    dateStyle: "medium",
  }).format(at);
}

/** Date and time, for the operator's log where two entries can share a day. */
export function formatDateTime(at: number): string {
  return new Intl.DateTimeFormat(LOCALE[getLang()], {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(at);
}
